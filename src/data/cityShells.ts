import type { CityBones, CityPalette, LandmarkKind } from "./types";

type StreetKind = "avenue" | "street" | "walk";

/** Real-US campaign identity. Google Maps/Satellite/Street View/Terrain are reference only — never scraped. */
export type ShellAnchor = {
  id: string;
  name: string;
  kind: string;
  /** Offset from the city's downtown lat/lon (degrees). */
  dLon: number;
  dLat: number;
};

export type ShellStreet = {
  name: string;
  kind: StreetKind;
  /** Half-length in degrees. ns = north-south avenue. */
  span: number;
  ns: boolean;
  shift?: number;
};

export type CityShell = {
  id: string;
  districts: string[];
  landmarkName: string;
  landmarkKind: LandmarkKind;
  skyline: string;
  bones: CityBones;
  palette: CityPalette;
  bestiaryPrefix: string;
  streets: ShellStreet[];
  anchors: ShellAnchor[];
};

function pal(
  sky: number,
  fog: number,
  buildings: number[],
  accent: number,
  plaza: number,
  grass: number,
  road: number,
  sidewalk: number,
  window: number,
  extra?: Pick<CityPalette, "night" | "neon">,
): CityPalette {
  return { sky, fog, buildings, accent, plaza, grass, road, sidewalk, window, ...extra };
}

