const byId = new Map(COMICS.map((c) => [c.id, c]));

export function comicById(id: string): ComicArc | undefined {
  return byId.get(id);
}

export function comicsForCity(cityId: string): ComicArc[] {
  return COMICS.filter((c) => c.cityId === cityId);
}

export function searchComics(query: string): ComicArc[] {
  const q = query.trim().toLowerCase();
  if (!q) return COMICS;
  return COMICS.filter(
    (c) =>
      c.title.toLowerCase().includes(q) ||
      c.era.toLowerCase().includes(q) ||
      c.cityId.replace(/-/g, " ").includes(q) ||
      c.codexTitle.toLowerCase().includes(q),
  );
}
