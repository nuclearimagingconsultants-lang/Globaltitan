import type { HulkKind } from "./types";

/** Public era / arc titles only. Mission copy is original. No comic dialogue. */
export type ComicBeatKind = "smash" | "reach" | "hold";

export type ComicBeat = {
  id: string;
  title: string;
  kind: ComicBeatKind;
};

export type ComicArc = {
  id: string;
  title: string;
  era: string;
  cityId: string;
  dungeon?: boolean;
  sky: number;
  fog: number;
  ground: number;
  accent: number;
  formHint?: Exclude<HulkKind, "bruce">;
  night?: boolean;
  beats: ComicBeat[];
  brief: string;
  returnBlurb: string;
  codexTitle: string;
  codexBody: string;
};

const SMASH: ComicBeat = { id: "smash", title: "Put the memory down", kind: "smash" };
const REACH: ComicBeat = { id: "reach", title: "Cross the instance", kind: "reach" };
const HOLD: ComicBeat = { id: "hold", title: "Hold the green", kind: "hold" };
const TWO: ComicBeat[] = [SMASH, REACH];
const THREE: ComicBeat[] = [SMASH, REACH, HOLD];

function arc(
  partial: Omit<ComicArc, "beats"> & { beats?: ComicBeat[] },
): ComicArc {
  return { beats: TWO, ...partial };
}

