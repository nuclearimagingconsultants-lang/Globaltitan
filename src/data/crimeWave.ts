export function crimeWaveById(id: string): CrimeWaveContact | undefined {
  return CRIME_WAVE_CONTACTS.find((c) => c.id === id);
}

export function crimeWaveByArchetype(archetype: CrimeWaveArchetype): CrimeWaveContact[] {
  return CRIME_WAVE_CONTACTS.filter((c) => c.archetype === archetype);
}

export function crimeWaveStatus(
  save: { completedQuests: string[]; activeQuestId: string | null },
  contact: CrimeWaveContact,
): "active" | "done" | "open" {
  if (save.activeQuestId === contact.id) return "active";
  if (save.completedQuests.includes(contact.id)) return "done";
  return "open";
}

